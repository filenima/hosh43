/**
 * تولید محتوای ترکیب شهر+صنف — همان بخش‌های غنیِ صنعت با
 * مقدمه/عاقبتِ اختصاصی شهر و ترتیب متفاوت برای هر شهر (کاهش duplicate content)
 */
export function generateCityIndustryLongform(
  industry: IndustryData,
  city: CityContextInfo
): LongformSection[] {
  const sections: LongformSection[] = [];
  sections.push(cityIntroSection(industry, city));
  sections.push(...generateIndustryLongform(industry, city.slug));
  // Task 24-SEO-PAGES: سکشن‌های یونیک {شهر}×{صنف} با دادهٔ واقعی شهر (جمعیت/صنف‌های رایج)
  sections.push(cityTaxSection(industry, city));
  sections.push(cityOpsSection(industry, city));
  sections.push(cityOutroSection(industry, city));
  // حذف جمع‌بندی عمومیِ longform صنعت (جایگزین: سکشن‌های شهر + outro)
  const deduped = sections.filter(
    (s, i) => !(i > 1 && i < sections.length - 1 && s.heading.startsWith("جمع‌بندی"))
  );
  return deduped;
}

/** شمارش تقریبی کلمات — HTML خام به متن تبدیل و سپس شمارده می‌شود */
export function estimateWordCount(sections: LongformSection[]): number {
  let words = 0;
  for (const s of sections) {
    if (s.heading) words += s.heading.split(/\s+/).filter(Boolean).length;
    for (const p of s.paragraphs || []) words += p.split(/\s+/).filter(Boolean).length;
    for (const b of s.bullets || []) words += b.split(/\s+/).filter(Boolean).length;
    if (s.html) words += s.html.replace(/<[^>]*>/g, " ").split(/\s+/).filter(Boolean).length;
  }
  return words;
}
