/** هش ساده از slug برای تنوع بخش‌ها */
function slugSeed(slug: string): number {
  let h = 0;
  for (let i = 0; i < slug.length; i++) h = (h * 31 + slug.charCodeAt(i)) >>> 0;
  return h;
}

/** PRNG قطعی برای به‌هم‌ریختن ترتیب بخش‌ها بر اساس slug */
function mulberry32(a: number): () => number {
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** به‌هم‌ریختن قطعی آرایه — برای یونیک‌بودن ترتیب بخش‌ها بین صنایع */
function seededShuffle<T>(items: T[], seed: number): T[] {
  const out = [...items];
  const rnd = mulberry32(seed);
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    const tmp = out[i];
    out[i] = out[j];
    out[j] = tmp;
  }
  return out;
}

/** انتخاب قطعی یکی از چند نسخه عبارت — برای تنوع لحن بین صفحات */
function pick<T>(variants: T[], seed: number, salt: number): T {
  return variants[(seed % 9973 + salt * 31) % variants.length];
}

