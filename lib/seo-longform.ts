export function generateIndustryLongform(
  industry: IndustryData,
  variantSeed?: string
): LongformSection[] {
  // variantSeed (مثل slug شهر) ترتیب بخش‌ها را برای هر ترکیب متفاوت می‌کند
  // تا صفحات شهر+صنف محتوای تکراریِ مو‌به‌مو نداشته باشند (SEO dedupe)
  const seed = slugSeed(industry.slug + (variantSeed ? `:${variantSeed}` : ""));
  const profile = getProfile(industry);
  const sections: LongformSection[] = [];

  // ---------- مقدمه و تحلیل (ابتدای ثابت صفحه) ----------
  sections.push(introSection(industry));
  sections.push(challengesSection(industry, seed));
  sections.push(modulesSection(industry, seed));

  // ---------- بخش‌های میانی — ترتیب با shuffle قطعی بر اساس slug ----------
  const middle: LongformSection[] = [
    legalChecklistSection(industry, profile, seed),
    routineSection(industry, profile, seed),
    fraudSection(industry, profile, seed),
    aiToolsSection(industry, profile, seed),
    faqSection(industry, profile, seed),
    excelCompareSection(industry, profile, seed),
    implementationSection(industry),
    tcoSection(industry),
    whySection(industry, seed),
    securitySection(industry),
    capabilitiesSection(),
    roadmapSection(industry),
    caseStudySection(industry),
  ];
  sections.push(...seededShuffle(middle, seed));

  // ---------- جمع‌بندی (انتهای ثابت صفحه) ----------
  sections.push(conclusionSection(industry));

  return sections;
}

