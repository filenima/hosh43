/** Task 24-SEO-PAGES: جمعیت شهر به ارقام فارسی — «۸٫۷ میلیون» یا «۷۰۰ هزار» */
function faPopulation(n?: number): string {
  if (!n || n <= 0) return "";
  const toFa = (x: string) => x.replace(/\d/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]);
  const millions = n / 1_000_000;
  if (millions >= 1) return `${toFa(millions.toFixed(1).replace(/\.0$/, ""))} میلیون`;
  return `${toFa(String(Math.round(n / 1000)))} هزار`;
}

