/** نرمال‌سازی ارقام فارسی/عربی به لاتین + فاصله‌های نیم */
function normalizeFa(text: string): string {
  return String(text || "")
    .replace(/[۰-۹]/g, (d) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(d)))
    .replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d)))
    .replace(/\u200c/g, " ")
    .replace(/\u200f|\u200e/g, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/** سال شمسی جاری (بدون وابستگی بیرونی — تقریب ۱ فروردین = ۲۱ مارس) */
function currentJalaliYear(): number {
  const now = new Date();
  const gy = now.getFullYear();
  const afterNowruz = now.getTime() >= new Date(gy, 2, 21).getTime();
  return gy - (afterNowruz ? 621 : 622);
}

/** استخراج عدد (تومان) از متن — «۲ میلیون»، «۵۰۰ هزار»، «۱۲۳۴۵۶۷»
 *  Task 25-C: مبالغ حروفی هم پشتیبانی می‌شود — «دو میلیون»، «بیست و پنج هزار تومان» */
function extractAmount(text: string): number | null {
  const t = normalizeFa(text);
  const m = t.match(/(\d+(?:[.,]\d+)?)\s*(میلیون|ملیون|میلیارد|هزار|تومان|تومن)?/);
  if (m) {
    let n = Number(m[1].replace(",", "."));
    if (!Number.isFinite(n)) return null;
    const unit = m[2] || "";
    if (unit.includes("میلیارد")) n *= 1_000_000_000;
    else if (unit.includes("میلیون") || unit.includes("ملیون")) n *= 1_000_000;
    else if (unit.includes("هزار")) n *= 1_000;
    return Math.round(n);
  }
  // رقم نبود — عدد به حروف («دو میلیون» / «پنجاه هزار تومان»)
  return extractWordAmount(t);
}

// ─── Task 25-C: عدد فارسی به حروف → رقم (کوچک، sync، بدون وابستگی) ───
const FA_WORD_UNITS: Record<string, number> = {
  "صفر": 0, "یک": 1, "یکی": 1, "دو": 2, "سه": 3, "چهار": 4, "پنج": 5,
  "شش": 6, "شیش": 6, "هفت": 7, "هشت": 8, "نه": 9, "ده": 10, "یازده": 11,
  "دوازده": 12, "سیزده": 13, "چهارده": 14, "پانزده": 15, "پونزده": 15,
  "شانزده": 16, "هفده": 17, "هجده": 18, "نوزده": 19,
};
const FA_WORD_TENS: Record<string, number> = {
  "بیست": 20, "سی": 30, "چهل": 40, "پنجاه": 50, "شصت": 60,
  "هفتاد": 70, "هشتاد": 80, "نود": 90,
};
const FA_WORD_HUNDREDS: Record<string, number> = {
  "صد": 100, "دویست": 200, "سیصد": 300, "چهارصد": 400, "پانصد": 500,
  "ششصد": 600, "هفتصد": 700, "هشتصد": 800, "نهصد": 900,
};

/** آیا توکن یک عدد به حروف/رابط «و» است؟ */
function isFaNumeralToken(w: string): boolean {
  return w === "و" || w in FA_WORD_HUNDREDS || w in FA_WORD_TENS || w in FA_WORD_UNITS;
}

/** پارس دنباله‌ای از اعداد حروفی («صد و بیست و پنج» → 125) — null اگر توکن غیرعددی وسط باشد */
function parseFaWordNumber(tokens: string[]): number | null {
  let current = 0;
  let any = false;
  for (const raw of tokens) {
    const w = raw.trim();
    if (w === "و") continue;
    if (w in FA_WORD_HUNDREDS) { current += FA_WORD_HUNDREDS[w]; any = true; continue; }
    if (w in FA_WORD_TENS) { current += FA_WORD_TENS[w]; any = true; continue; }
    if (w in FA_WORD_UNITS) { current += FA_WORD_UNITS[w]; any = true; continue; }
    return null;
  }
  return any ? current : null;
}

/** استخراج مبلغ حروفی از جمله نرمال‌شده — «دو میلیون» → 2000000 */
function extractWordAmount(t: string): number | null {
  const tokens = t.split(/\s+/).filter(Boolean);
  for (let i = 0; i < tokens.length; i++) {
    if (!isFaNumeralToken(tokens[i]) || tokens[i] === "و") continue;
    let j = i;
    while (j < tokens.length && isFaNumeralToken(tokens[j])) j++;
    const value = parseFaWordNumber(tokens.slice(i, j));
    if (value !== null && value > 0) {
      const unit = tokens[j] ?? "";
      let n = value;
      if (unit.includes("میلیارد")) n *= 1_000_000_000;
      else if (unit.includes("میلیون") || unit.includes("ملیون")) n *= 1_000_000;
      else if (unit.includes("هزار")) n *= 1_000;
      return Math.round(n);
    }
    i = j - 1;
  }
  return null;
}

/** Task 25-C: استخراج درصد — «۲۰ درصد»، «۱۵٪»، «10%» */
function extractPercent(text: string): number | null {
  const t = normalizeFa(text);
  const m = t.match(/(\d+(?:[.,]\d+)?)\s*(?:درصدی|درصد|٪|%)/);
  if (!m) return null;
  const n = Number(m[1].replace(",", "."));
  return Number.isFinite(n) ? n : null;
}

/** Task 25-C: استخراج شماره فاکتور — «۱۴۰۵-۰۰۰۱۲» / «فاکتور 1405-3» */
function extractInvoiceNumber(text: string): string | null {
  const t = normalizeFa(text);
  const m = t.match(/(\d{4})\s*-\s*(\d{1,6})\b/);
  if (!m) return null;
  return `${m[1]}-${m[2]}`;
}

/** Task 25-C: استخراج تعداد روز — «۳ روز دیگه»، «۱۰ روز بعد» */
function extractDays(text: string): number | null {
  const t = normalizeFa(text);
  const m = t.match(/(\d+)\s*روز/);
  if (!m) return null;
  const n = Number(m[1]);
  return Number.isFinite(n) && n > 0 && n <= 365 ? n : null;
}

/** استخراج نام شخص بعد از «برای/به نام/به اسم/مشتری/از/به» */
function extractParty(text: string): string | null {
  const t = normalizeFa(text);
  const patterns = [
    /(?:برای|به نام|به اسم|به|از|مشتری|طرف حساب|تامین کننده|تأمین کننده|فروشنده|خریدار)\s+([آ-ی ءؤئ a-z0-9]{2,30}?)(?=\s+(?:با|به|مبلغ|خرید|بزن|ثبت|فاکتور|یک|دو|سه|چند|\d|دریافت|پرداخت|وصول|تسویه|$|،|,))/,
  ];
  for (const p of patterns) {
    const m = t.match(p);
    if (m?.[1]) {
      const name = m[1]
        .trim()
        .replace(/^(خانم|آقای|من|او)\s+/, "")
        .replace(/\s+(مبلغ|تومان|تومن|میلیون|هزار)$/u, "")
        .trim();
      if (name.length >= 2 && !/^(مبلغ|تومان|تومن|چقدر|چند)$/.test(name)) return name;
    }
  }
  return null;
}

/** استخراج اقلام «۲ تا شیر ۵۰ هزار» یا «شیر ۵۰۰۰۰ تومان» */
function extractItems(text: string): Array<{ name: string; quantity: number; unitPrice: number }> {
  const items: Array<{ name: string; quantity: number; unitPrice: number }> = [];
  const t = normalizeFa(text);
  const re =
    /(\d+)\s*(?:تا|عدد|بسته|کیلو)?\s*([آ-ی ءؤئ]{2,25}?)\s*(\d+(?:[.,]\d+)?)\s*(میلیون|میلیارد|هزار|تومان|تومن)?/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(t)) !== null) {
    const quantity = Number(m[1]) || 1;
    const name = m[2].trim();
    let unitPrice = Number(m[3].replace(",", "."));
    const unit = m[4] || "";
    if (unit.includes("میلیارد")) unitPrice *= 1_000_000_000;
    else if (unit.includes("میلیون")) unitPrice *= 1_000_000;
    else if (unit.includes("هزار")) unitPrice *= 1_000;
    if (name.length >= 2 && Number.isFinite(unitPrice) && unitPrice > 0) {
      items.push({ name, quantity, unitPrice });
    }
    if (items.length >= 8) break;
  }
  return items;
}

/** Task 25-C: نام شل بعد از «روی/برای/برای کالای» — برای تخفیف («۲۰ درصد تخفیف روی شیر بذار») */
function extractLooseName(text: string): string | null {
  const t = normalizeFa(text);
  const m = t.match(
    /(?:روی|روی\s*کالای|برای\s*کالای|کالای|کالا|محصول|جنس)\s+([آ-ی ءؤئ a-z0-9]{2,30}?)(?=\s*(?:\d|درصد|تخفیف|بذار|بزار|کن|ثبت|اعمال|بگذار|گذار|تا|و|،|,|$))/
  );
  if (m?.[1]) {
    const name = m[1].trim();
    if (name.length >= 2 && !/^(درصد|تخفیف|مبلغ|تومان)$/.test(name)) return name;
  }
  return null;
}

/** استخراج نام کالا — بعد از «کالای/کالا/محصول/جنس» تا کلمه محدودکننده */
function extractProductName(text: string): string | null {
  const t = normalizeFa(text);
  const m = t.match(
    /(?:کالای|کالا|محصول|جنس)\s+([آ-ی ءؤئ a-z0-9]{2,40}?)(?=\s*(?:را|چقدر|چند|است|هست|بگو|ببین|نشان|پیدا|موجودی|قیمت|شد|بساز|اضافه|کم|تا|برای|به|با|و|\d|،|,|$))/
  );
  if (m?.[1]) {
    const name = m[1].trim();
    if (name.length >= 2) return name;
  }
  // fallback: قبل از «چقدر است/چند است» — «موجودی آب رنگ چقدر است؟»
  const m2 = t.match(/(?:موجودی|قیمت)\s+([آ-ی ءؤئ a-z0-9 ]{2,40}?)(?=\s*(?:چقدر|چند|است|هست|شد|بگو))/);
  if (m2?.[1]) {
    const name = m2[1].trim();
    if (name.length >= 2) return name;
  }
  return null;
}

/** استخراج تعداد — «۵ تا»، «۱۰ عدد»، «۳ بسته» */
function extractQuantity(text: string): number | null {
  const t = normalizeFa(text);
  const m = t.match(/(\d+(?:[.,]\d+)?)\s*(?:تا|عدد|بسته|کیلو|لیتر|لین|گرم|کارتن|جین)/);
  if (!m) return null;
  const n = Number(m[1].replace(",", "."));
  return Number.isFinite(n) ? n : null;
}

/** استخراج بازه دوره: این ماه/ماه قبل/امسال/همیشه */
function extractPeriod(text: string): string {
  const t = normalizeFa(text);
  if (t.includes("ماه قبل") || t.includes("ماه گذشته") || t.includes("ماه پیش")) return "last_month";
  if (t.includes("امسال") || t.includes("این سال") || t.includes("سال جاری")) return "this_year";
  if (t.includes("همیشه") || t.includes("کل") || t.includes("تاریخچه")) return "all";
  return "this_month";
}

/** استخراج تاریخ شمسی سررسید — «۲۰ اسفند»، «۱۴۰۵/۰۳/۲۰» */
function extractDueDate(text: string): string | null {
  const t = normalizeFa(text);
  const iso = t.match(/(1[34]\d{2})\s*[\/\-\.]\s*(\d{1,2})\s*[\/\-\.]\s*(\d{1,2})/);
  if (iso) return `${iso[1]}/${iso[2].padStart(2, "0")}/${iso[3].padStart(2, "0")}`;
  const named = t.match(
    /(\d{1,2})\s*(فروردین|اردیبهشت|خرداد|تیر|مرداد|شهریور|مهر|آبان|آذر|دی|بهمن|اسفند)/
  );
  if (named) {
    const months: Record<string, number> = {
      فروردین: 1,
      اردیبهشت: 2,
      خرداد: 3,
      تیر: 4,
      مرداد: 5,
      شهریور: 6,
      مهر: 7,
      آبان: 8,
      آذر: 9,
      دی: 10,
      بهمن: 11,
      اسفند: 12,
    };
    const m = months[named[2]];
    if (m) return `${currentJalaliYear()}/${String(m).padStart(2, "0")}/${named[1].padStart(2, "0")}`;
  }
  return null;
}

