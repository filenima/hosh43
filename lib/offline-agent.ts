function faDigits(n: number | string): string {
  return String(n).replace(/[0-9]/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[Number(d)]);
}

/** فرمت امن مبلغ */
function faMoney(v: unknown): string {
  if (v === null || v === undefined) return "—";
  if (typeof v === "string") return v; // fmt() قبلاً قالب‌بندی کرده
  const n = Number(v);
  if (!Number.isFinite(n)) return String(v);
  return faDigits(new Intl.NumberFormat("fa-IR").format(Math.round(n)));
}

/** جدول مارک‌داون از آرایه اشیاء */
function mdTable(rows: Array<Record<string, unknown>>, maxRows = 10): string {
  if (!rows.length) return "";
  const keys = Object.keys(rows[0]).filter((k) => k !== "note").slice(0, 6);
  const head = `| ${keys.map((k) => FIELD_FA[k] || k).join(" | ")} |`;
  const sep = `| ${keys.map(() => "---").join(" | ")} |`;
  const body = rows
    .slice(0, maxRows)
    .map(
      (r) =>
        `| ${keys
          .map((k) => {
            const v = r[k];
            if (v === null || v === undefined) return "—";
            if (typeof v === "number") return faMoney(v);
            if (typeof v === "boolean") return v ? "بله" : "—";
            return String(v);
          })
          .join(" | ")} |`
    )
    .join("\n");
  return [head, sep, body].join("\n");
}

/** جمله بولت از شیء */
function kvBullets(obj: Record<string, unknown>, skip: string[] = []): string {
  const keys = Object.keys(obj).filter(
    (k) => !skip.includes(k) && k !== "note" && obj[k] !== null && obj[k] !== undefined
  );
  return keys
    .slice(0, 12)
    .map((k) => {
      const v = obj[k];
      const label = FIELD_FA[k] || k;
      if (Array.isArray(v)) return `- **${label}:** ${faDigits(v.length)} مورد`;
      if (typeof v === "object" && v !== null) return `- **${label}:** ${faDigits(Object.keys(v).length)} فیلد`;
      if (typeof v === "number") return `- **${label}:** ${faMoney(v)}`;
      if (typeof v === "boolean") return `- **${label}:** ${v ? "بله" : "خیر"}`;
      return `- **${label}:** ${String(v)}`;
    })
    .join("\n");
}

/** بلوک «در دفاتر چه گذشت» برای نتایج ثبت (فقط فکت‌های واقعیِ خروجی ابزار) */
function ledgerEffectsBlock(result: Record<string, unknown>): string {
  const lines: string[] = [];
  const invoice = (result.invoice ?? null) as Record<string, unknown> | null;
  if (invoice) {
    const reserved = String(invoice.status ?? "") === "RESERVED";
    const credit = String(invoice.paymentType ?? "") === "CREDIT";
    const journalPosted = invoice.journalPosted === true;
    const stockItems = Number(invoice.stockLinkedItems ?? 0);
    if (reserved) {
      lines.push("- رزرو است: هنوز **سند حسابداری و حرکت انبار ثبت نشده** — با «نهایی‌سازی» فعال می‌شود");
    } else {
      if (journalPosted) lines.push("- سند حسابداری خودکار در دفتر روزنامه صادر و ثبت شد");
      if (stockItems > 0)
        lines.push(`- حرکت انبار (خروج/ورود) برای ${faDigits(stockItems)} قلم کالا ثبت شد`);
      if (credit) lines.push("- روی حساب «طلب از مشتری / بدهی به تأمین‌کننده» قطع‌نشان شد (سررسید فعال شد)");
    }
  }
  const payment = (result.payment ?? null) as Record<string, unknown> | null;
  if (payment) {
    lines.push("- مانده فاکتور به‌روز شد و وضعیت پرداخت تازه شد");
  }
  const product = (result.product ?? null) as Record<string, unknown> | null;
  if (product && (result.stockAdjusted === true || result.stockMoved === true)) {
    lines.push("- ردیف کاردکس (StockMovement) ثبت و بهای میانگین متحرک بازمحاسبه شد");
  }
  if (result.expense) {
    lines.push("- در دفتر هزینه‌ها ثبت شد (وضعیت اولیه: در انتظار تأیید)");
  }
  // Task 25-C: یادآور و ابطال پیش‌نویس
  if (result.reminder) {
    lines.push("- یادآور در ماژول «یادآورها» ثبت شد و سررسیدش در همان‌جا دیده می‌شود");
  }
  if (result.voided === true) {
    lines.push("- پیش‌نویس ابطال شد (وضعیت CANCELLED) — چون پیش‌نویس بود، سند/انبار اثری نداشت که خنثی شود");
  }
  if (!lines.length) return "";
  return `\n\n**در دفاتر چه گذشت:**\n${lines.join("\n")}`;
}

/** کارت راهنمای ماژول — گام‌های شماره‌دار (بدون ایموجی) */
function helpCardMarkdown(card: OfflineHelpCard): string {
  const steps = card.steps.map((s, i) => `${faDigits(i + 1)}. ${s}`).join("\n");
  return (
    `### ${card.fa}\n\n` +
    `${card.desc}\n\n` +
    `- **کجاست:** ${card.where}\n` +
    `- **API مربوط:** ${card.api}\n\n` +
    `**نکته‌ها و گام‌ها:**\n${steps}`
  );
}

/**
 * قالب‌بندی پاسخ آفلاین — متن فارسی غنی از نتیجه واقعی ابزار.
 * defensive: هر شکلی از داده را بدون کرش رندر می‌کند.
 */
export function formatOfflineReply(
  intent: OfflineIntent,
  results: Array<{ tool: string; result: Record<string, unknown> }>,
  opts: { tenantName?: string } = {}
): string {
  const parts: string[] = [];

  // کارت راهنما (سوال «کجاست/چطور») — پیش از نتایج ابزار
  if (intent.help) {
    parts.push(helpCardMarkdown(intent.help));
  }

  for (const { tool, result } of results) {
    if (!result) continue;
    const err = result.error ? String(result.error) : null;

    switch (tool) {
      case "query_kpis": {
        if (err) { parts.push(`خواندن شاخص‌ها ممکن نشد: ${err}`); break; }
        parts.push(
          `### وضعیت مالی (${result.periodLabel ? String(result.periodLabel) : "این ماه"})\n\n` +
            kvBullets(result, ["period", "periodLabel", "currency"]) +
            `\n\nسود = فروش − خرید − هزینه‌ها. برای تحلیل عمیق‌تر بگویید «مطالباتم را نشان بده» یا «هزینه‌هایم را تحلیل کن».`
        );
        break;
      }
      case "query_invoices": {
        const rows = (result.invoices as Array<Record<string, unknown>>) || [];
        if (err || rows.length === 0) {
          parts.push(
            `در بازه خواسته‌شده فاکتوری ${err ? "خوانده نشد" : "پیدا نشد"} — می‌توانید بگویید «فاکتورهای قرضی» یا «فاکتورهای این ماه».`
          );
          break;
        }
        parts.push(`### فاکتورها (${faDigits(rows.length)} مورد)\n\n` + mdTable(rows));
        break;
      }
      case "query_parties": {
        const rows = (result.parties as Array<Record<string, unknown>>) || [];
        if (err || rows.length === 0) {
          parts.push("طرف‌حسابی با این فیلتر پیدا نشد — با بخشی از نام امتحان کنید.");
          break;
        }
        parts.push(`### طرف‌حساب‌ها (${faDigits(rows.length)})\n\n` + mdTable(rows));
        break;
      }
      case "query_products": {
        const rows = (result.products as Array<Record<string, unknown>>) || [];
        if (err || rows.length === 0) {
          parts.push("کالایی یافت نشد — با نام یا SKU بگویید.");
          break;
        }
        parts.push(`### کالاها (${faDigits(rows.length)})\n\n` + mdTable(rows));
        break;
      }
      case "query_warehouse": {
        const rows =
          (result.items as Array<Record<string, unknown>>) ||
          (result.rows as Array<Record<string, unknown>>) ||
          [];
        if (err || rows.length === 0) {
          parts.push("موجودی‌ای برای نمایش نیست — اولین رسید ورود را ثبت کنیم؟");
          break;
        }
        const low = String(result.lowStockCount ?? result.lowStock ?? "");
        parts.push(
          `### موجودی انبار (${faDigits(rows.length)} قلم)\n\n` +
            mdTable(rows) +
            (low && low !== "0" ? `\n\nتوجه: ${faDigits(low)} قلم زیر نقطه سفارش مجدد است — سفارش خرید را همین حالا ببندیم؟` : "")
        );
        break;
      }
      case "query_currency": {
        const rows = (result.rates as Array<Record<string, unknown>>) || (result.items as Array<Record<string, unknown>>) || [];
        if (rows.length > 0) {
          parts.push(`### نرخ‌های لحظه‌ای\n\n` + mdTable(rows));
        } else {
          parts.push(`### نرخ‌های لحظه‌ای\n\n` + kvBullets(result));
        }
        break;
      }
      case "query_expenses": {
        const rows = (result.expenses as Array<Record<string, unknown>>) || [];
        if (err || rows.length === 0) {
          parts.push("هزینه‌ای در این فیلتر نیست.");
          break;
        }
        parts.push(
          `### هزینه‌ها (${faDigits(rows.length)} مورد — جمع ${faMoney(result.totalToman ?? 0)} تومان)\n\n` + mdTable(rows)
        );
        break;
      }
      case "query_treasury": {
        const rows = (result.accounts as Array<Record<string, unknown>>) || [];
        if (rows.length > 0) {
          parts.push(`### خزانه — حساب‌های بانکی\n\n` + mdTable(rows));
        } else {
          parts.push(`### خزانه\n\n` + kvBullets(result));
        }
        break;
      }
      case "query_modian": {
        parts.push(`### سامانه مودیان\n\n` + kvBullets(result, ["note"]));
        break;
      }
      case "query_credit_receivables": {
        const rows = (result.invoices as Array<Record<string, unknown>>) || (result.items as Array<Record<string, unknown>>) || [];
        if (rows.length > 0) {
          parts.push(`### مطالبات قرضی/نسیه\n\n` + mdTable(rows));
        } else {
          parts.push(`### مطالبات\n\n` + kvBullets(result, ["note"]));
        }
        break;
      }
      // ─── راند ۲۴: ابزارهای داده‌ای جدید ───
      case "query_top_products": {
        const rows = (result.products as Array<Record<string, unknown>>) || [];
        if (err || rows.length === 0) {
          parts.push(`در این بازه فروشی ثبت نشده تا پرفروش‌ها را ببینیم.`);
          break;
        }
        parts.push(
          `### پرفروش‌ترین کالاها (${result.periodLabel ? String(result.periodLabel) : "بازه"})\n\n` + mdTable(rows)
        );
        break;
      }
      case "query_top_debtors": {
        const rows = (result.debtors as Array<Record<string, unknown>>) || [];
        if (err || rows.length === 0) {
          parts.push("هیچ طرف‌حسابی بدهی باز ندارد — عالی است.");
          break;
        }
        parts.push(`### بیشترین بدهکاران\n\n` + mdTable(rows));
        break;
      }
      case "query_profit_report": {
        if (err) { parts.push(`محاسبه سود ممکن نشد: ${err}`); break; }
        parts.push(
          `### گزارش سود (${result.periodLabel ? String(result.periodLabel) : "بازه"})\n\n` +
            kvBullets(result, ["period", "periodLabel", "currency", "note"]) +
            `\n\nسود خالص = فروش − خرید − هزینه‌ها. مالیات ارزش افزوده فروش جدا نگه داشته می‌شود چون به شما تعلق ندارد.`
        );
        break;
      }
      case "query_inventory_value": {
        if (err) { parts.push(`ارزش‌گذاری انبار ممکن نشد: ${err}`); break; }
        const top = (result.topItems as Array<Record<string, unknown>>) || [];
        parts.push(
          `### ارزش موجودی انبار\n\n` + kvBullets(result, ["currency", "note", "topItems"]) +
            (top.length ? `\n\n**باارزش‌ترین اقلام:**\n\n` + mdTable(top, 5) : "")
        );
        break;
      }
      case "query_budget": {
        if (err) { parts.push(`خواندن بودجه ممکن نشد: ${err}`); break; }
        const rows = (result.budgets as Array<Record<string, unknown>>) || [];
        if (rows.length > 0) {
          parts.push(`### وضعیت بودجه\n\n` + mdTable(rows));
        } else {
          parts.push("هنوز بودجه‌ای تعریف نشده — ماژول بودجه‌ریزی (گروه انبار و کالا) را باز کنیم؟");
        }
        break;
      }
      case "query_wallet": {
        if (err) { parts.push(`خواندن کیف پول ممکن نشد: ${err}`); break; }
        const rows = (result.transactions as Array<Record<string, unknown>>) || [];
        parts.push(
          `### کیف پول\n\n` + kvBullets(result, ["currency", "note", "transactions"]) +
            (rows.length ? `\n\n**آخرین تراکنش‌ها:**\n\n` + mdTable(rows, 5) : "")
        );
        break;
      }
      // ─── Task 25-C: ابزارهای داده‌ای جدید ───
      case "query_receivables_payables": {
        if (err) { parts.push(`دادهای برای محاسبه مطالبات و بدهی‌ها در دسترس نیست: ${err}`); break; }
        const aging = (result.aging as Array<Record<string, unknown>>) || [];
        const topParties = (result.topParties as Array<Record<string, unknown>>) || [];
        parts.push(
          `### مطالبات و بدهی‌ها (با سن بدهی)\n\n` +
            kvBullets(result, ["currency", "note", "aging", "topParties"]) +
            (aging.length ? `\n\n**تفکیک سنتی:**\n\n` + mdTable(aging) : "") +
            (topParties.length ? `\n\n**طرف‌حساب‌های با بیشترین مانده:**\n\n` + mdTable(topParties, 5) : "")
        );
        break;
      }
      case "query_cashflow": {
        if (err) { parts.push(`دادهای برای محاسبه جریان نقدی در دسترس نیست: ${err}`); break; }
        parts.push(
          `### جریان نقدی (${result.periodLabel ? String(result.periodLabel) : "این ماه"})\n\n` +
            kvBullets(result, ["period", "periodLabel", "currency", "note"])
        );
        break;
      }
      case "query_top_customers": {
        const rows = (result.customers as Array<Record<string, unknown>>) || [];
        if (err || rows.length === 0) {
          parts.push("هنوز فروشی ثبت نشده تا بهترین مشتری‌ها را ببینیم.");
          break;
        }
        parts.push(`### برترین مشتری‌ها (بر اساس مبلغ خرید)\n\n` + mdTable(rows));
        break;
      }
      case "query_top_vendors": {
        const rows = (result.vendors as Array<Record<string, unknown>>) || [];
        if (err || rows.length === 0) {
          parts.push("هنوز خریدی ثبت نشده تا بهترین تأمین‌کننده‌ها را ببینیم.");
          break;
        }
        parts.push(`### برترین تأمین‌کننده‌ها (بر اساس مبلغ خرید شما)\n\n` + mdTable(rows));
        break;
      }
      case "query_party_balance": {
        if (err) { parts.push(`خواندن مانده طرف‌حساب ممکن نشد: ${err}`); break; }
        const party = (result.party as Record<string, unknown>) || null;
        const oldest = (result.oldestOpenInvoice as Record<string, unknown>) || null;
        parts.push(
          `### مانده طرف‌حساب${party ? ` — ${String(party.name ?? "")}` : ""}\n\n` +
            kvBullets(result, ["currency", "note", "party", "oldestOpenInvoice"]) +
            (oldest ? `\n\n**قدیمی‌ترین فاکتور باز:**\n\n` + kvBullets(oldest) : "")
        );
        break;
      }
      case "query_invoice_stats": {
        if (err) { parts.push(`دادهای برای محاسبه آمار فاکتورها در دسترس نیست: ${err}`); break; }
        const sales = (result.sales as Record<string, unknown>) || {};
        const purchases = (result.purchases as Record<string, unknown>) || {};
        parts.push(
          `### آمار فاکتورها — این ماه در برابر ماه قبل\n\n` +
            `**فروش:**\n\n` + kvBullets(sales) +
            `\n\n**خرید:**\n\n` + kvBullets(purchases)
        );
        break;
      }
      case "query_expense_breakdown": {
        if (err) { parts.push(`دادهای برای تحلیل هزینه‌ها در دسترس نیست: ${err}`); break; }
        const byCat = (result.byCategory as Array<Record<string, unknown>>) || [];
        const rows = (result.expenses as Array<Record<string, unknown>>) || [];
        parts.push(
          `### تفکیک هزینه‌ها (${result.periodLabel ? String(result.periodLabel) : "این ماه"})\n\n` +
            kvBullets(result, ["period", "periodLabel", "currency", "note", "expenses", "byCategory"]) +
            (byCat.length ? `\n\n**بر اساس دسته:**\n\n` + mdTable(byCat) : "") +
            (rows.length ? `\n\n**بزرگ‌ترین ردیف‌ها:**\n\n` + mdTable(rows, 8) : "")
        );
        break;
      }
      case "query_slow_stock": {
        if (err) { parts.push(`دادهای برای محاسبه کالاهای کم‌حرکت در دسترس نیست: ${err}`); break; }
        const rows = (result.items as Array<Record<string, unknown>>) || [];
        if (rows.length === 0) {
          parts.push(
            `### کالاهای کم‌حرکت\n\nکالای با موجودی مثبتی که بیش از ${faDigits(String(result.daysThreshold ?? 45))} روز حرکت نداشته پیدا نشد — انبار پویاست.`
          );
          break;
        }
        parts.push(
          `### کالاهای کم‌حرکت (${faDigits(rows.length)} قلم)\n\n` + mdTable(rows)
        );
        break;
      }
      case "query_vat_summary": {
        if (err) { parts.push(`دادهای برای محاسبه مالیات ارزش افزوده در دسترس نیست: ${err}`); break; }
        parts.push(
          `### مالیات ارزش افزوده (${result.periodLabel ? String(result.periodLabel) : "این ماه"})\n\n` +
            kvBullets(result, ["period", "periodLabel", "currency", "note"])
        );
        break;
      }
      case "query_profit_trend": {
        if (err) { parts.push(`دادهای برای محاسبه روند سود در دسترس نیست: ${err}`); break; }
        const months = (result.months as Array<Record<string, unknown>>) || [];
        const trend = result.trendLine ? String(result.trendLine) : "";
        parts.push(
          `### روند سود ۶ ماه اخیر\n\n` +
            (trend ? `\`${trend}\`\n\n` : "") +
            (months.length ? mdTable(months) : "در ۶ ماه اخیر دادهای برای محاسبه سود ثبت نشده است.")
        );
        break;
      }
      case "query_employee_count": {
        if (err) { parts.push(`دادهای پرسنلی در دسترس نیست: ${err}`); break; }
        const byType = (result.byContractType as Array<Record<string, unknown>>) || [];
        parts.push(
          `### کارکنان\n\n` +
            kvBullets(result, ["currency", "note", "byContractType"]) +
            (byType.length ? `\n\n**بر اساس نوع قرارداد:**\n\n` + mdTable(byType) : "")
        );
        break;
      }
      case "query_payroll_total": {
        if (err) { parts.push(`دادهای حقوق و دستمزد در دسترس نیست: ${err}`); break; }
        if (result.payslipCount === 0 || result.empty === true) {
          parts.push("هنوز هیچ فیش حقوقی ثبت نشده — از ماژول حقوق و دستمزد دوره را بسازیم؟");
          break;
        }
        parts.push(`### حقوق و دستمزد — آخرین دوره (${result.periodLabel ?? ""})\n\n` + kvBullets(result, ["period", "periodLabel", "currency", "note"]));
        break;
      }
      case "create_opening_balance_hint": {
        const steps = (result.steps as string[]) || [];
        parts.push(
          `### ${result.title ? String(result.title) : "راهنمای ثبت موجودی اولیه"}\n\n` +
            (result.desc ? String(result.desc) + "\n\n" : "") +
            steps.map((s, i) => `${faDigits(i + 1)}. ${s}`).join("\n")
        );
        break;
      }
      case "search_help": {
        const excerpt = result.excerpt ? String(result.excerpt) : "";
        const topics = (result.topics as Array<{ module: string; how: string }>) || [];
        if (topics.length > 0) {
          parts.push(
            `### راهنمای گام‌به‌گام\n\n` +
              topics
              .slice(0, 3)
              .map((tp) => `**${tp.module}** — ${tp.how}`)
              .join("\n\n")
          );
        } else if (excerpt) {
          const clean = excerpt.replace(/<[^>]+>/g, " ").replace(/\s+/g, " ").trim();
          parts.push(`### راهنما\n\n` + clean.slice(0, 1200) + (clean.length > 1200 ? "…" : ""));
        } else {
          parts.push(
            `### راهنما\n\nدر اسناد راهنما پاسخ مستقیمی پیدا نشد؛ اما می‌توانم سوال را دقیق‌تر بپرسید یا خودم همان کار را همین‌جا انجام بدهم.`
          );
        }
        break;
      }
      case "navigate": {
        const moduleSlug = String(result.module ?? "");
        const moduleFa = MODULE_KB.find((e) => e.module === moduleSlug)?.fa ?? moduleSlug;
        parts.push(`مسیر را برایتان باز کردم — «${moduleFa || moduleSlug}» را در پنل ببینید.`);
        break;
      }
      default: {
        // ابزارهای ثبت — پاسخ در result
        if (err) {
          parts.push(`خطا: ${err}`);
          break;
        }
        // باز کردن شیء تو در تو (invoice/expense/party/product/payment/reminder) برای نمایش غنی
        const nested = ["invoice", "expense", "party", "product", "payment", "reminder"] as const;
        let nestedShown = false;
        for (const key of nested) {
          const inner = result[key];
          if (inner && typeof inner === "object") {
            const created =
              result.created === true || result.updated === true ? "ثبت/به‌روزرسانی انجام شد:\n\n" : "";
            const dupWarn = result.duplicateWarning ? `\n\nتوجه: ${String(result.duplicateWarning)}` : "";
            parts.push(
              `### ${created}${FIELD_FA[key] || key}\n\n` +
                kvBullets(inner as Record<string, unknown>, [
                  "invoiceId",
                  "partyId",
                  "productId",
                  "expenseId",
                  "url",
                  // فیلدهای فنی که متن کاربر را شلوغ می‌کنند (در بلوک دفاتر/کارت اجرا می‌روند)
                  "mode",
                  "changed",
                  "movementId",
                  "stockMoved",
                  "stockAdjusted",
                  "journalPosted",
                  "stockLinkedItems",
                  "appliedToOldestOpenInvoice",
                  "direction",
                  "existing",
                  "usdPriceUpdated",
                ]) +
                ledgerEffectsBlock(result) +
                dupWarn
            );
            nestedShown = true;
            break;
          }
        }
        if (!nestedShown) {
          parts.push(`### نتیجه اجرا\n\n` + kvBullets(result, ["success"]) + ledgerEffectsBlock(result));
        }
      }
    }
  }

  const footer =
    `\n\n---\n` +
    `*پاسخ از **موتور محلی هوش‌یار** تولید شد (بدون API خارجی — روی داده واقعی ${opts.tenantName || "کسب‌وکار شما"} اجرا شد).* ` +
    `برای پاسخ‌های محاوره‌ای‌تر، موتور ابری در دسترس است؛ اما همین موتور محلی همه کارهای اجرایی را کامل انجام می‌دهد: ` +
    `ثبت (فاکتور نقدی/قرضی/رزرو، هزینه، مشتری، کالا، موجودی، قیمت، تخفیف کالا، دریافت/پرداخت، یادآور، ابطال پیش‌نویس) و ` +
    `خواندن داده (سود و روند سود، جریان نقدی، مطالبات و بدهی با سن بدهی، مانده طرف‌حساب، آمار فاکتور، تحلیل هزینه، ارزش و کم‌حرکت‌های انبار، ` +
    `ارزش افزوده، برترین مشتری/تأمین‌کننده/کالا/بدهکار، بودجه، کیف پول، حقوق و پرسنل) و ناوبری/راهنمای ۲۸+ ماژول.`;

  const body = parts.filter(Boolean).join("\n\n");
  return (body || "پیام شما دریافت شد — بگویید چه کاری انجام بدهم (مثلاً «فاکتور بزن» یا «فروش این ماه چقدر بود؟»).") + footer;
}
