async function seed() {
 let seeded = 0;
 let skipped = 0;

 for (const article of articles) {
 try {
 const existing = await db.blogPost.findUnique({ where: { slug: article.slug } });
 if (existing) {
 skipped++;
 continue;
 }

 // تاریخ انتشار پلکانی برای تازگی نسبی
 const daysAgo = articles.length - articles.indexOf(article);
 const publishedAt = new Date(Date.now() - daysAgo * 3 * 24 * 60 * 60 * 1000);

 await db.blogPost.create({
 data: {
 title: article.title,
 slug: article.slug,
 excerpt: article.excerpt,
 content: article.content,
 coverImage: article.coverImage,
 metaTitle: article.metaTitle,
 metaDescription: article.metaDescription,
 focusKeyword: article.focusKeyword,
 tags: article.tags,
 category: article.category,
 readingTime: article.readingTime,
 status: article.status,
 publishedAt,
 },
 });
 seeded++;
 } catch {
 skipped++;
 }
 }

 return NextResponse.json({
 success: true,
 seeded,
 skipped,
 total: articles.length,
 message: `${seeded} مقاله جدید ثبت شد و ${skipped} مقاله از قبل وجود داشت`,
 });
}

export async function GET(request: Request) {
 const url = new URL(request.url);
 const secret = url.searchParams.get("secret");
 const isDev = process.env.NODE_ENV === "development";

 if (!isDev && secret!== process.env.SEED_SECRET) {
 return NextResponse.json({ error: "دسترسی غیرمجاز" }, { status: 403 });
 }

 return seed();
}

